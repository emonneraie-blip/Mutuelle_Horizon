-- BRONZE layer of the Mutuelle Horizon Santé fraud platform.
-- Bronze keeps the data AS RECEIVED (text columns), plus lineage columns:
--   _SOURCE_FILE, _FILE_ROW, _BATCH_DATE, _LOADED_AT, _RUN_ID
-- Run by `python -m jobs.bootstrap_bronze` (idempotent). Database, warehouse and roles are created by Terraform.

CREATE SCHEMA IF NOT EXISTS BRONZE;

CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ENCODING = 'UTF8' EMPTY_FIELD_AS_NULL = FALSE ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE FILE FORMAT IF NOT EXISTS BRONZE.FF_JSON TYPE = JSON STRIP_OUTER_ARRAY = FALSE;

CREATE STAGE IF NOT EXISTS BRONZE.LANDING COMMENT = 'Landing zone: raw files as received, partitioned by source and date';

-- Optical claims (tiers payant + adherent app), one file per day, CSV
CREATE TABLE IF NOT EXISTS BRONZE.FACTURES_OPTIQUE (
  ID_DEMANDE VARCHAR, CANAL VARCHAR, DATE_RECEPTION VARCHAR, NUMERO_FACTURE VARCHAR, SIRET_OPTICIEN VARCHAR,
  NOM_OPTICIEN VARCHAR, RPPS_PRESCRIPTEUR VARCHAR, DATE_PRESCRIPTION VARCHAR, NUM_ADHERENT VARCHAR,
  NIR_BENEFICIAIRE VARCHAR, DATE_SOINS VARCHAR, DATE_FACTURE VARCHAR, TYPE_EQUIPEMENT VARCHAR, CLASSE VARCHAR,
  CATEGORIE_VERRES VARCHAR, MONTANT_MONTURE VARCHAR, MONTANT_VERRES VARCHAR, MONTANT_TOTAL VARCHAR,
  BASE_REMBOURSEMENT_RO VARCHAR, MONTANT_REMBOURSE_RO VARCHAR, MONTANT_DEMANDE_AMC VARCHAR,
  _SOURCE_FILE VARCHAR, _FILE_ROW NUMBER, _BATCH_DATE DATE, _LOADED_AT TIMESTAMP_TZ, _RUN_ID VARCHAR
);

-- Sécurité sociale statements (NOEMIE flow), one JSON document per line
CREATE TABLE IF NOT EXISTS BRONZE.NOEMIE_DECOMPTES (
  RAW VARIANT, _SOURCE_FILE VARCHAR, _FILE_ROW NUMBER, _BATCH_DATE DATE, _LOADED_AT TIMESTAMP_TZ, _RUN_ID VARCHAR
);

-- Adherents and contracts, pulled incrementally from the CRM (Postgres), latest version per adherent
-- Minimised copy of the CRM: only what the rules need (F3: FORMULE, F7: DATE_FIN_CONTRAT).
-- No NIR, name, birth date, e-mail, phone, postcode or city.
CREATE TABLE IF NOT EXISTS BRONZE.ADHERENTS (
  ID_ADHERENT VARCHAR, FORMULE VARCHAR, DATE_DEBUT_CONTRAT DATE, DATE_FIN_CONTRAT DATE, STATUT VARCHAR,
  UPDATED_AT TIMESTAMP_NTZ, _LOADED_AT TIMESTAMP_TZ, _RUN_ID VARCHAR
);
CREATE TRANSIENT TABLE IF NOT EXISTS BRONZE.ADHERENTS_STG LIKE BRONZE.ADHERENTS;

-- SIRENE checks of the opticians seen in the claims (API recherche-entreprises), one row per SIRET
CREATE TABLE IF NOT EXISTS BRONZE.SIRENE_ETABLISSEMENTS (
  SIRET VARCHAR, FOUND BOOLEAN, ETAT_ADMINISTRATIF VARCHAR, ACTIVITE_PRINCIPALE VARCHAR, RAW VARIANT,
  _CHECKED_AT TIMESTAMP_TZ, _RUN_ID VARCHAR
);

-- Ophthalmologists from the RPPS directory (Annuaire Santé open data). No names: data minimisation.
CREATE TABLE IF NOT EXISTS BRONZE.RPPS_PRESCRIPTEURS (
  RPPS VARCHAR, CODE_PROFESSION VARCHAR, LIBELLE_PROFESSION VARCHAR, CODE_SAVOIR_FAIRE VARCHAR,
  LIBELLE_SAVOIR_FAIRE VARCHAR, CODE_POSTAL VARCHAR, COMMUNE VARCHAR,
  _SOURCE_FILE VARCHAR, _FILE_ROW NUMBER, _LOADED_AT TIMESTAMP_TZ, _RUN_ID VARCHAR
);

-- One row per job run: what was loaded, when, by which run (observability, replay, freshness)
CREATE TABLE IF NOT EXISTS BRONZE.LOAD_AUDIT (
  RUN_ID VARCHAR, JOB VARCHAR, BATCH_DATE VARCHAR, STATUS VARCHAR, FILES_LOADED NUMBER, ROWS_LOADED NUMBER,
  STARTED_AT TIMESTAMP_TZ, ENDED_AT TIMESTAMP_TZ, DETAILS VARIANT
);

-- Hand-off to the transformation layer: INGEST_ROLE owns BRONZE and gives READ access to TRANSFORM_ROLE (created by Terraform).
-- Run again after adding a table (bootstrap is idempotent).
GRANT USAGE ON SCHEMA BRONZE TO ROLE TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA BRONZE TO ROLE TRANSFORM_ROLE;
